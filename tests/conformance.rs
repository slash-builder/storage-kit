//! Storage Kit's first CI-enforced conformance gate.
//!
//! Imports the frozen `spec_kit::conformance::{Case, run_suite}` harness
//! (from the `slashbuilder-spec-kit` crate on crates.io) and exercises
//! storage-kit's own invariants: the same-bytes-same-address guarantee, hash
//! verification on every read, and fragment-tree round-tripping. This is the
//! first crate in the SlashBuilder Kit ecosystem to wire spec-kit's
//! conformance ABI end to end against a real engine — "locked"
//! starts meaning enforced, not just documented.
//!
//! **Interface-lock gate (2026-08-26).** Per the kit-lock bar, this suite
//! must run as a genuinely *external* consumer of the crate — hence
//! `tests/`, not `#[cfg(test)]` — and it must reach for **nothing but the
//! crate-root re-exports**. The `use storage_kit::{…}` line below is
//! deliberately flat: no `storage_kit::fragment::…` or
//! `storage_kit::store::…` module paths. If a future case cannot be
//! written against the root re-exports alone, that is the signal that the
//! frozen surface is incomplete — fix `lib.rs`, do not deepen the import.

use spec_kit::conformance::{run_suite, Case};
use std::fs::OpenOptions;
use std::io::{Read, Seek, SeekFrom, Write};
use storage_kit::{
    build_fragment_tree, list_partitions, read_fragment_tree, walk_hashes, ChunkingProfile,
    EncryptionMode, Hash, ImmutableStore, PartitionId, PartitionSpec, PartitionStore,
    RetentionClass, Subject, SubjectKind,
};
use tempfile::tempdir;

/// Deterministic, high-entropy filler bytes, generated by chaining
/// `Hash::of` (storage-kit's own public hashing primitive) rather than
/// pulling in a separate RNG dependency. High entropy matters for the
/// integrity-gate case: it keeps the payload effectively incompressible so
/// a corrupted byte can't accidentally decode/hash back to the original.
fn entropy_bytes(seed: &str, len: usize) -> Vec<u8> {
    let mut out = Vec::with_capacity(len + 32);
    let mut block = Hash::of(seed.as_bytes());
    while out.len() < len {
        out.extend_from_slice(block.as_bytes());
        block = Hash::of(block.as_bytes());
    }
    out.truncate(len);
    out
}

/// Provision a fresh person partition for `name`. `PartitionStore::open`
/// no longer creates a partition on first use (spec §3.7), so every case
/// below that wants a working store must provision one explicitly.
fn create_person_partition(dir: &std::path::Path, name: &str) -> Result<PartitionStore, String> {
    let partition_id = PartitionId::for_person(name);
    let spec = PartitionSpec {
        subject: Subject {
            kind: SubjectKind::Person,
            id: name.to_string(),
        },
        retention_class: RetentionClass::Standard,
        encryption_mode: EncryptionMode::Plaintext,
        label: None,
    };
    PartitionStore::create(dir, partition_id, spec).map_err(|e| e.to_string())
}

/// Case 1: bytes written with `put` come back byte-identical from `get`.
struct RoundTrip;
impl Case for RoundTrip {
    fn name(&self) -> &str {
        "storage-kit::round-trip put-then-get returns identical bytes"
    }
    fn run(&self) -> Result<(), String> {
        let dir = tempdir().map_err(|e| e.to_string())?;
        let mut store = create_person_partition(dir.path(), "conformance-round-trip")?;
        let data = entropy_bytes("round-trip", 4096);

        let hash = store.put(&data).map_err(|e| e.to_string())?;
        let back = store.get(&hash).map_err(|e| e.to_string())?;
        if back != data {
            return Err("get() did not return the exact bytes put()".into());
        }
        Ok(())
    }
}

/// Case 2: `Hash::of` is a pure function of the bytes — stable across
/// repeated calls, and `put` addresses identical bytes identically
/// (including the dedup path on a repeat `put`).
struct ContentAddressDeterminism;
impl Case for ContentAddressDeterminism {
    fn name(&self) -> &str {
        "storage-kit::content-address determinism: Hash::of is stable and same bytes address identically"
    }
    fn run(&self) -> Result<(), String> {
        let data = entropy_bytes("determinism", 8192);

        let h1 = Hash::of(&data);
        let h2 = Hash::of(&data);
        if h1 != h2 {
            return Err("Hash::of(same bytes) produced different hashes across calls".into());
        }

        let dir = tempdir().map_err(|e| e.to_string())?;
        let mut store = create_person_partition(dir.path(), "conformance-determinism")?;
        let put_hash = store.put(&data).map_err(|e| e.to_string())?;
        if put_hash != h1 {
            return Err(
                "store.put()'s returned hash disagrees with Hash::of() on the same bytes".into(),
            );
        }

        // A second put of the same bytes must land on the same address
        // (per-partition dedup), not a distinct one.
        let put_hash_again = store.put(&data).map_err(|e| e.to_string())?;
        if put_hash_again != h1 {
            return Err("re-putting identical bytes produced a different address".into());
        }
        Ok(())
    }
}

/// Case 3: the integrity gate — corrupting a stored block's bytes on disk
/// must make `get` reject it, never silently return corrupt bytes.
struct IntegrityGate;
impl Case for IntegrityGate {
    fn name(&self) -> &str {
        "storage-kit::integrity gate rejects a block corrupted on disk"
    }
    fn run(&self) -> Result<(), String> {
        let dir = tempdir().map_err(|e| e.to_string())?;
        let mut store = create_person_partition(dir.path(), "conformance-integrity")?;
        let data = entropy_bytes("integrity-gate", 2048);
        let hash = store.put(&data).map_err(|e| e.to_string())?;

        // The active pack has no trailer yet (trailers are only written on
        // seal), so the last byte on disk is the last byte of the single
        // entry we just appended — flip it in place to corrupt the block.
        let active_pack = store.partition_root().join("active").join("active.pack");
        let mut file = OpenOptions::new()
            .read(true)
            .write(true)
            .open(&active_pack)
            .map_err(|e| e.to_string())?;
        let len = file.metadata().map_err(|e| e.to_string())?.len();
        if len == 0 {
            return Err("active pack is empty; nothing to corrupt".into());
        }
        file.seek(SeekFrom::End(-1)).map_err(|e| e.to_string())?;
        let mut last = [0u8; 1];
        file.read_exact(&mut last).map_err(|e| e.to_string())?;
        file.seek(SeekFrom::End(-1)).map_err(|e| e.to_string())?;
        file.write_all(&[last[0] ^ 0xFF])
            .map_err(|e| e.to_string())?;
        drop(file);

        match store.get(&hash) {
            Ok(bytes) => Err(format!(
                "get() returned {} corrupted bytes instead of rejecting them",
                bytes.len()
            )),
            Err(_) => Ok(()),
        }
    }
}

/// Case 4: `build_fragment_tree` followed by `read_fragment_tree` reproduces
/// the original input exactly, across a large enough input to force
/// multiple leaves folded through at least one list-node level.
struct FragmentTreeRoundTrip;
impl Case for FragmentTreeRoundTrip {
    fn name(&self) -> &str {
        "storage-kit::fragment-tree round-trip reproduces the input bytes"
    }
    fn run(&self) -> Result<(), String> {
        let dir = tempdir().map_err(|e| e.to_string())?;
        let mut store = create_person_partition(dir.path(), "conformance-fragment-tree")?;

        let data = entropy_bytes("fragment-tree", 300_000);
        let profile = ChunkingProfile::Fixed { block_size: 4096 };
        let tree = build_fragment_tree(&data, &profile, &mut store).map_err(|e| e.to_string())?;

        let back = read_fragment_tree(tree.root, tree.depth, &store).map_err(|e| e.to_string())?;
        if back != data {
            return Err(
                "read_fragment_tree did not reproduce the bytes build_fragment_tree stored".into(),
            );
        }
        Ok(())
    }
}

/// Case 7 (T-replacement, condition of the 2026-09-23 rulings) — the
/// tripwire this case replaces was `tests/conformance.rs:177-193`'s
/// "every Address is anonymous" assertion, which lost its subject when
/// `Context`/`Address` were retired from the engine. Deleting a live
/// enforcement mechanism without a replacement would have been a net loss
/// of enforcement even though the ruling that removed the types is
/// correct — both rulings say so explicitly and make the replacement a
/// condition, not a nice-to-have.
///
/// This is the 2026-06 storage lock's own sentence, rendered as a test:
/// "same bytes, different contexts = same payload deduplicated under one
/// hash." Two `put`s of identical plaintext into one partition must yield
/// **exactly one physical entry**, not merely the same returned hash —
/// asserting only equal hashes would pass even if the engine wrote two
/// entries and happened to return the same address for both.
struct DedupIsOnePhysicalEntry;
impl Case for DedupIsOnePhysicalEntry {
    fn name(&self) -> &str {
        "storage-kit::same bytes in one partition dedup to exactly one physical entry (2026-06 lock, executable)"
    }
    fn run(&self) -> Result<(), String> {
        let dir = tempdir().map_err(|e| e.to_string())?;
        let mut store = create_person_partition(dir.path(), "conformance-one-physical-entry")?;
        let data = entropy_bytes("one-physical-entry", 4096);

        let h1 = store.put(&data).map_err(|e| e.to_string())?;
        let h2 = store.put(&data).map_err(|e| e.to_string())?;
        if h1 != h2 {
            return Err("two puts of identical plaintext produced different content ids".into());
        }
        if store.active_entry_count() != 1 {
            return Err(format!(
                "two puts of identical plaintext produced {} physical entries, not 1 — the \
                 storage key has been composited on something beyond hash alone",
                store.active_entry_count()
            ));
        }
        Ok(())
    }
}

/// Case 8 (T-A, security review §5.4) — no unauthenticated caller-supplied
/// value appears in any cleartext pack/idx header. `content_id` is the sole
/// caller-influenced field (it is a pure function of the plaintext); every
/// other field is store-set or mechanical. This is the byte-level half of
/// the replacement tripwire: it fails the day anyone adds a new cleartext
/// entry field carrying a caller value (a resurrected `context`, a label, a
/// scope tag — anything).
struct NoUnauthenticatedCleartextField;
impl Case for NoUnauthenticatedCleartextField {
    fn name(&self) -> &str {
        "storage-kit::no unauthenticated caller-supplied value in any cleartext entry header (D-2a)"
    }
    fn run(&self) -> Result<(), String> {
        use storage_kit::packfile;

        let dir = tempdir().map_err(|e| e.to_string())?;
        let mut store = create_person_partition(dir.path(), "conformance-no-cleartext-field")?;
        let data = entropy_bytes("no-cleartext-field", 4096);
        let hash = store.put(&data).map_err(|e| e.to_string())?;
        store.seal_active().map_err(|e| e.to_string())?;

        // Re-derive the entry straight from the sealed pack's own bytes —
        // deliberately bypassing `get()` so this assertion is about what is
        // physically on disk, not about what a trusting reader chooses to
        // interpret.
        let pack_path = store
            .sealed_pack_ids()
            .first()
            .ok_or("expected one sealed pack")?
            .to_hex();
        let pack_path = dir
            .path()
            .join(store.partition_id().to_hex())
            .join("packs")
            .join(&pack_path[..2])
            .join(format!("{pack_path}.pack"));
        let entries = packfile::rebuild_index_entries(&pack_path).map_err(|e| e.to_string())?;
        let (_, meta) = entries
            .into_iter()
            .find(|(_, m)| m.hash == hash)
            .ok_or("entry not found in rebuilt index")?;

        // The only cleartext value that may depend on the caller's bytes at
        // all is `hash`, and it must equal the unkeyed BLAKE3 commitment to
        // exactly what was put — nothing else about it is caller-chosen.
        if meta.hash != storage_kit::Hash::of(&data) {
            return Err("entry hash is not the plaintext's own content hash".into());
        }
        // Every other field is store-set or mechanical: reserved-value at
        // v3, and never a value a caller passed in.
        if meta.flags != 0x00 {
            return Err(format!("flags is non-reserved: {:#04x}", meta.flags));
        }
        if meta.key_epoch != 0 {
            return Err(format!("key_epoch is non-reserved: {}", meta.key_epoch));
        }
        if meta.uncompressed_len != data.len() as u64 {
            return Err("uncompressed_len does not match the mechanical plaintext length".into());
        }
        Ok(())
    }
}

/// Case 9 (T-B, security review §5.4) — no free-form logical-identity
/// constructor exists on the public surface, other than `PartitionId`,
/// whose use is gated by `PartitionStore::create`'s derivation check
/// against the closed `subject.kind` vocabulary. This is the mechanical
/// form of the guardrail argument both rulings make: a field minted inline
/// from an arbitrary caller string has no moment at which anyone can be
/// made to justify a value, so it cannot be guarded — only asked nicely
/// about. Scans this crate's own `src/` tree so a reintroduced `Context`
/// (or any other un-gated `pub fn derive(&str)`-shaped constructor) fails
/// the build here rather than drifting past review.
struct NoFreeFormIdentityConstructor;
impl Case for NoFreeFormIdentityConstructor {
    fn name(&self) -> &str {
        "storage-kit::no free-form logical-identity constructor on the public surface, other than PartitionId (T-B)"
    }
    fn run(&self) -> Result<(), String> {
        let src_dir = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("src");
        let mut offenders = Vec::new();

        fn visit(dir: &std::path::Path, offenders: &mut Vec<String>) -> Result<(), String> {
            for entry in std::fs::read_dir(dir).map_err(|e| e.to_string())? {
                let entry = entry.map_err(|e| e.to_string())?;
                let path = entry.path();
                if path.is_dir() {
                    visit(&path, offenders)?;
                    continue;
                }
                if path.extension().and_then(|e| e.to_str()) != Some("rs") {
                    continue;
                }
                let text = std::fs::read_to_string(&path).map_err(|e| e.to_string())?;

                // `Context`/`Address` must not exist at all.
                for banned in ["struct Context", "struct Address"] {
                    if text.contains(banned) {
                        offenders.push(format!("{}: reintroduces `{banned}`", path.display()));
                    }
                }

                // Track which `impl <Type>` block each line sits in, so a
                // free-form-string constructor can be attributed to its
                // type. Only `PartitionId::derive` may exist.
                let mut current_impl: Option<String> = None;
                for line in text.lines() {
                    let trimmed = line.trim_start();
                    if let Some(rest) = trimmed.strip_prefix("impl ") {
                        // "impl PartitionId {" / "impl Foo for Bar {" —
                        // take the last identifier before "{" or "for".
                        let head = rest.split('{').next().unwrap_or(rest).trim();
                        let type_name = head.split(" for ").next().unwrap_or(head).trim();
                        current_impl = Some(
                            type_name
                                .split_whitespace()
                                .next()
                                .unwrap_or("")
                                .to_string(),
                        );
                    }
                    if trimmed.starts_with("pub fn derive(")
                        || trimmed.starts_with("fn derive(")
                        || trimmed.starts_with("pub fn from_str(")
                    {
                        let owner = current_impl.clone().unwrap_or_else(|| "<unknown>".into());
                        if owner != "PartitionId" {
                            offenders.push(format!(
                                "{}: free-form identity constructor `{}` on `{owner}`, only \
                                 `PartitionId::derive` may exist",
                                path.display(),
                                trimmed.trim_end()
                            ));
                        }
                    }
                }
            }
            Ok(())
        }

        visit(&src_dir, &mut offenders)?;
        if !offenders.is_empty() {
            return Err(offenders.join("; "));
        }
        Ok(())
    }
}

/// Case 5: the GC-reachability invariant — every hash `walk_hashes` reaches
/// from a tree root is actually resident in the store, and the partition
/// the tree was written into is discoverable by `list_partitions`. This is
/// the contract bitchain's mark-and-sweep GC depends on: the mark phase
/// must never name a block the sweep phase can't find.
struct ReachabilityAndPartitionDiscovery;
impl Case for ReachabilityAndPartitionDiscovery {
    fn name(&self) -> &str {
        "storage-kit::GC reachability: walked hashes are resident and the partition is discoverable"
    }
    fn run(&self) -> Result<(), String> {
        let dir = tempdir().map_err(|e| e.to_string())?;
        let mut store = create_person_partition(dir.path(), "conformance-reachability")?;
        let partition_id = store.partition_id();

        let data = entropy_bytes("reachability", 300_000);
        let profile = ChunkingProfile::Fixed { block_size: 4096 };
        let tree = build_fragment_tree(&data, &profile, &mut store).map_err(|e| e.to_string())?;

        if tree.depth == 0 {
            return Err("expected a folded tree (depth >= 1) for this input size".into());
        }

        let mut live: Vec<Hash> = Vec::new();
        walk_hashes(tree.root, tree.depth, &store, &mut live).map_err(|e| e.to_string())?;

        if live.first() != Some(&tree.root) {
            return Err("walk_hashes did not report the root as the first reached hash".into());
        }
        if live.len() < 2 {
            return Err("walk_hashes reached only the root of a folded tree".into());
        }
        for h in &live {
            if !store.has(h) {
                return Err(format!(
                    "walk_hashes reached {h}, which the store does not have — \
                     a GC mark phase would name a block sweep cannot find"
                ));
            }
        }

        let partitions = list_partitions(dir.path()).map_err(|e| e.to_string())?;
        if !partitions.contains(&partition_id) {
            return Err("list_partitions did not discover the partition just written".into());
        }
        Ok(())
    }
}

/// Case 6: the retention-symmetry guardrail (spec §4.3) — a person
/// partition and a household partition, provisioned with otherwise
/// identical specs, must be structurally indistinguishable: identical
/// acceptance (both succeed or both fail) and byte-identical
/// `partition.json` modulo `partition_id` and `created_at`, for **every**
/// retention class. `PartitionStore` never sees a `Subject` at all — see
/// `storage_kit::partition`'s module docs — so there is no code path left
/// that could special-case one over the other without changing a function
/// signature.
///
/// This case does not assert on `GcReport`, unlike the spec's literal
/// wording: GC lives in `bitchain`, not in this crate, and this change is
/// scoped to the partition record and provisioning API only.
struct PersonHouseholdRetentionSymmetry;
impl Case for PersonHouseholdRetentionSymmetry {
    fn name(&self) -> &str {
        "storage-kit::retention class is structurally identical for person and household partitions, across every class"
    }
    fn run(&self) -> Result<(), String> {
        use serde_json::Value;

        for retention_class in [
            RetentionClass::Ephemeral,
            RetentionClass::Standard,
            RetentionClass::Durable,
        ] {
            let dir = tempdir().map_err(|e| e.to_string())?;
            let person_id = PartitionId::for_person("conformance-symmetry-acct");
            let household_id = PartitionId::for_household("conformance-symmetry-hid");

            let person_spec = PartitionSpec {
                subject: Subject {
                    kind: SubjectKind::Person,
                    id: "conformance-symmetry-acct".to_string(),
                },
                retention_class,
                encryption_mode: EncryptionMode::Plaintext,
                label: None,
            };
            let household_spec = PartitionSpec {
                subject: Subject {
                    kind: SubjectKind::Household,
                    id: "conformance-symmetry-hid".to_string(),
                },
                retention_class,
                encryption_mode: EncryptionMode::Plaintext,
                label: None,
            };

            let person_result = PartitionStore::create(dir.path(), person_id, person_spec);
            let household_result = PartitionStore::create(dir.path(), household_id, household_spec);

            if person_result.is_ok() != household_result.is_ok() {
                return Err(format!(
                    "{retention_class:?}: person and household provisioning diverged — person: {:?}, household: {:?}",
                    person_result.is_ok(),
                    household_result.is_ok(),
                ));
            }
            let person_store = person_result.map_err(|e| e.to_string())?;
            let household_store = household_result.map_err(|e| e.to_string())?;

            let person_json =
                std::fs::read_to_string(person_store.partition_root().join("partition.json"))
                    .map_err(|e| e.to_string())?;
            let household_json =
                std::fs::read_to_string(household_store.partition_root().join("partition.json"))
                    .map_err(|e| e.to_string())?;

            let mut person_value: Value =
                serde_json::from_str(&person_json).map_err(|e| e.to_string())?;
            let mut household_value: Value =
                serde_json::from_str(&household_json).map_err(|e| e.to_string())?;
            for value in [&mut person_value, &mut household_value] {
                if let Some(obj) = value.as_object_mut() {
                    obj.remove("partition_id");
                    obj.remove("created_at");
                }
            }
            if person_value != household_value {
                return Err(format!(
                    "{retention_class:?}: partition.json diverged between person and household \
                     modulo partition_id/created_at — person: {person_value}, household: {household_value}"
                ));
            }
            if person_store.retention_class() != retention_class
                || household_store.retention_class() != retention_class
            {
                return Err(format!(
                    "{retention_class:?}: retention_class() did not round-trip through create()"
                ));
            }
        }
        Ok(())
    }
}

#[test]
fn storage_kit_conformance_suite() {
    let cases: Vec<Box<dyn Case>> = vec![
        Box::new(RoundTrip),
        Box::new(ContentAddressDeterminism),
        Box::new(IntegrityGate),
        Box::new(FragmentTreeRoundTrip),
        Box::new(ReachabilityAndPartitionDiscovery),
        Box::new(PersonHouseholdRetentionSymmetry),
        Box::new(DedupIsOnePhysicalEntry),
        Box::new(NoUnauthenticatedCleartextField),
        Box::new(NoFreeFormIdentityConstructor),
    ];
    let case_refs: Vec<&dyn Case> = cases.iter().map(|c| c.as_ref()).collect();
    let report = run_suite(&case_refs);

    for (name, err) in &report.failed {
        eprintln!("FAILED conformance case {name}: {err}");
    }
    assert!(
        report.is_success(),
        "{} of {} conformance cases failed: {:?}",
        report.failed.len(),
        report.total(),
        report.failed
    );
}
